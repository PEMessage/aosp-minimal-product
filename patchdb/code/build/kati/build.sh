#!/usr/bin/env bash
# Build ckati from source with the AOSP prebuilt clang.
#
# Toolchain: prebuilts/clang/host/linux-x86/clang-r416183b1 — the Android 12
# (S) clang, same era as the prebuilt ckati in prebuilts/build-tools.
#
# Why not the host g++ (GCC 15): modern libstdc++ stopped transitively
# including <cstdint> / <algorithm>, so kati-2021 fails to compile:
#     src/exec.cc:129: error: 'uint64_t' does not name a type
#     src/eval.cc:576: error: 'find_if' is not a member of 'std'
# AOSP always built ckati with its own clang; we do the same. The bundled
# libc++ headers are picked up automatically by `-stdlib=libc++`
# (<toolchain>/include/c++/v1), no -nostdinc++/-isystem wiring needed.
#
# Link-time notes:
#   -fuse-ld=lld: same as soong (build/soong/cc/config/global.go passes it
#     for device AND host). Without it the clang driver falls back to `ld`
#     found on PATH — here the host binutils ld.bfd. The toolchain's own
#     ld.lld sits next to clang, so no extra search path is needed.
#   -Wl,-rpath,$TC/lib64: runtime lookup of the toolchain's libc++.so.1
#     (same trick as the prebuilt ckati, which rpaths its own lib64).
#     Everything else resolves via the conventional FHS layout:
#       /usr/lib/gcc/<triple>/<ver>/  crtbegin.o + libgcc.a
#                                     (flake.nix targetPkgs gcc.cc — note
#                                     the plain `gcc` wrapper pkg does NOT
#                                     merge its lib/gcc into the env)
#       /usr/lib64                    crt1.o, crti.o (glibc.dev)
#       /usr/include                  glibc headers (glibc.dev)
#     The prebuilt clang itself ships no crt/libgcc — AOSP takes them from
#     prebuilts/gcc/.../x86_64-linux-glibc2.17-4.8, a repo this minimal
#     tree does not sync; the FHS gcc stands in for it.
#
# Everything else keeps the Makefile.ckati defaults: objects in ./out,
# binary at ./ckati, flags -g -W -Wall -MMD -MP -O -DNOLOG -march=native.
# Unlike the prebuilt (version_unknown.cc -> kGitVersion="unknown"), this
# build embeds the real commit: version.cc is generated from
# `git rev-parse HEAD`, so the binary writes "# Generated by kati <sha>"
# into the ninja files it produces.
#
# If `bear` is on PATH, the make step runs under it and a
# compile_commands.json lands in this directory for clangd/clang-tidy. It is
# built with `bear --append`, not a plain overwrite: `make` recompiles
# nothing when the tree is already up to date, and a plain `bear --output`
# would then replace a good database with []. Appending merges incremental
# rebuilds and leaves the file alone on a no-op run.
#
# The database is then post-processed to make the compiler absolute. bear
# stores only the basename (`clang++`): the AOSP launcher re-execs the real
# clang-12 with argv[0]="clang++", and that is the exec bear records. clangd
# resolves a bare name through PATH -- in the dev shell that is the Nix GCC
# wrapper, not the prebuilt clang -- so `-stdlib=libc++` resolves against
# nothing and every include (<string>, <limits.h>, ...) is "file not found".
# Pinning $TC/bin/clang++ lets clangd drive the prebuilt toolchain directly;
# no project .clangd / --query-driver is needed.
#
# The entries also get `-idirafter <glibc-dev include>`. On the NixOS host
# (clangd outside `nix develop`) there is no /usr/include, so libc++ header
# chains dead-end in glibc (<features.h>, <stdio.h>, ...) and clangd reports
# dozens of errors; inside the FHS the driver finds /usr/include on its own.
# Pointing at the real glibc-dev tree makes the database work in both. It has
# to be -idirafter (lowest priority): with -isystem it outranks clang's builtin
# <math.h> and leaves a "no member named 'signbit'" error.
#
# Requires the FHS dev shell (glibc headers + crt objects for linking):
#   nix develop
#   cd code/build/kati && ./build.sh
#
# Managed by patchman in copy mode: patchdb/code/build/kati/build.sh.
set -euo pipefail

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TOP="$(cd "$DIR/../.." && pwd)"  # code/

TC="$TOP/prebuilts/clang/host/linux-x86/clang-r416183b1"

if [[ ! -x "$TC/bin/clang++" ]]; then
    echo "error: $TC/bin/clang++ missing" >&2
    echo "       repo sync -c prebuilts/clang/host/linux-x86" >&2
    exit 1
fi

# NB: the target is $KATI_BIN_PATH/ckati = ./ckati (Makefile.ckati has no
# bare "ckati" target; "ckati" and "./ckati" are different target names).
cd "$DIR"

make_args=(
    -f Makefile.ckati ./ckati
    -j 4
    KATI_CXX="$TC/bin/clang++ -stdlib=libc++"
    KATI_LD="$TC/bin/clang++ -stdlib=libc++ -fuse-ld=lld -Wl,-rpath,$TC/lib64"
)

if command -v bear >/dev/null 2>&1; then
    bear --append --output "$DIR/compile_commands.json" -- make "${make_args[@]}"

    # /usr/include is a merged dir in the FHS; features.h resolves back to the
    # glibc-dev store tree, which is what clangd needs outside the FHS too.
    glibc_inc=""
    if [[ -r /usr/include/features.h ]]; then
        glibc_inc="$(dirname "$(readlink -f /usr/include/features.h)")"
    fi

    # Rewrite argv[0] of every entry to the absolute prebuilt clang++ and
    # (re)inject the glibc include (see the header comment). Injecting is
    # idempotent: any -idirafter pair already present is dropped first, so a
    # re-run does not grow the arguments. A second copy of a file (from an
    # incremental rebuild) is collapsed by bear on the next --append read.
    python3 - "$DIR/compile_commands.json" "$TC/bin/clang++" "$glibc_inc" <<'PY'
import json, sys

path, cxx, glibc_inc = sys.argv[1], sys.argv[2], sys.argv[3]
with open(path) as f:
    db = json.load(f)
for entry in db:
    args, clean, i = entry["arguments"], [], 0
    args[0] = cxx
    while i < len(args):  # drop a previously injected -idirafter pair
        if args[i] == "-idirafter" and i + 1 < len(args):
            i += 2
        else:
            clean.append(args[i])
            i += 1
    if glibc_inc:
        clean[1:1] = ["-idirafter", glibc_inc]
    entry["arguments"] = clean
with open(path, "w") as f:
    json.dump(db, f, indent=2)
    f.write("\n")
PY
else
    make "${make_args[@]}"
fi

# Install into prebuilts: soong_ui always execs
# prebuilts/build-tools/linux-x86/bin/ckati (PrebuiltBuildTool), there is no
# rebuild-from-source path in build/make, so the debug build must land there.
# The stock prebuilt is backed up once; restore with
#   cp prebuilts/build-tools/linux-x86/bin/ckati.prebuilt.bak \
#      prebuilts/build-tools/linux-x86/bin/ckati
# (a `repo sync prebuilts/build-tools` also restores it, since prebuilts is
# its own git repo — re-run this script afterwards).
DEST="$TOP/prebuilts/build-tools/linux-x86/bin/ckati"
if [[ ! -f "$DEST.prebuilt.bak" ]]; then
    cp -p "$DEST" "$DEST.prebuilt.bak"
fi
install -m 0755 ckati "$DEST"
echo "installed: $DEST (stock prebuilt kept at $DEST.prebuilt.bak)"
